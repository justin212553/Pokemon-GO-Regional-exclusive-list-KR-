// ── 판정 함수 ───────────────────────────────────
const polyBounds = new WeakMap();
function pointInPoly(poly, lat, lng) {
  let b = polyBounds.get(poly);
  if (!b) {
    b = [Infinity, -Infinity, Infinity, -Infinity];
    for (const [y, x] of poly) {
      if (y < b[0]) b[0] = y; if (y > b[1]) b[1] = y;
      if (x < b[2]) b[2] = x; if (x > b[3]) b[3] = x;
    }
    polyBounds.set(poly, b);
  }
  if (lat < b[0] || lat > b[1] || lng < b[2] || lng > b[3]) return false;
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [yi, xi] = poly[i];
    const [yj, xj] = poly[j];
    if ((yi > lat) !== (yj > lat) && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function inArea(expr, lat, lng) {
  if (typeof expr === 'string') {
    const def = AREAS[expr];
    if (!def) throw new Error('알 수 없는 지역: ' + expr);
    return inArea(def, lat, lng);
  }
  if (expr.band) {
    const [a, b, c, d] = expr.band;
    return lat >= a && lat <= b && lng >= c && lng <= d;
  }
  if (expr.poly) return pointInPoly(expr.poly, lat, lng);
  if (expr.polys) return expr.polys.some((p) => pointInPoly(p, lat, lng));
  if (expr.all && !expr.all.every((e) => inArea(e, lat, lng))) return false;
  if (expr.any && !expr.any.some((e) => inArea(e, lat, lng))) return false;
  if (expr.not && expr.not.some((e) => inArea(e, lat, lng))) return false;
  return !!(expr.all || expr.any);
}
